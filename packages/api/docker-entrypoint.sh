#!/usr/bin/env sh
# Точка входа контейнера.
#
# Миграции накатываются ОТДЕЛЬНЫМ одноразовым запуском того же образа (сервис
# `migrate` в compose, Job-хук в Helm-чарте), а не здесь. Причина: при
# нескольких репликах каждая пыталась бы мигрировать параллельно и они бы
# блокировали друг друга на DDL-локах.
#
# RUN_MIGRATIONS=1 оставлен как удобство для одиночных запусков, где отдельный
# шаг разводить незачем. В compose и k8s он НЕ используется.

set -eu

if [ "${RUN_MIGRATIONS:-0}" = "1" ]; then
  echo "Накатываю миграции..."
  alembic upgrade head
fi

exec "$@"
